export function calculateCourseFee(
  course: Course,
  profile: CreditProfile,
  useCredit = true
): FeeBreakdown & { openingCreditUsed: number; midCareerCreditUsed: number } {
  const tierConfig = RESIDENCY_TIER_INFO[profile.tier];
  const subsidyRate = course.ssgSubsidised ? tierConfig.subsidyRate : 0;
  const subsidyAmount = Math.round(course.fullFee * subsidyRate);
  const feeAfterSubsidy = Math.max(0, course.fullFee - subsidyAmount);

  let midCareerCreditUsed = 0;
  let openingCreditUsed = 0;

  if (useCredit && course.skillsFutureCreditEligible && feeAfterSubsidy > 0) {
    let remainingToCover = feeAfterSubsidy;

    if (course.midCareerTopUpEligible && profile.midCareerCreditBalance > 0) {
      midCareerCreditUsed = Math.min(remainingToCover, profile.midCareerCreditBalance);
      remainingToCover -= midCareerCreditUsed;
    }

    if (remainingToCover > 0 && profile.openingCreditBalance > 0) {
      openingCreditUsed = Math.min(remainingToCover, profile.openingCreditBalance);
      remainingToCover -= openingCreditUsed;
    }
  }

  const creditApplied = midCareerCreditUsed + openingCreditUsed;
  const outOfPocket = Math.max(0, feeAfterSubsidy - creditApplied);

  let creditSourceLabel = 'No credit applied';
  if (midCareerCreditUsed > 0 && openingCreditUsed > 0) {
    creditSourceLabel = 'Mid-Career + Opening Credit';
  } else if (midCareerCreditUsed > 0) {
    creditSourceLabel = 'Mid-Career Credit (40+)';
  } else if (openingCreditUsed > 0) {
    creditSourceLabel = 'SkillsFuture Credit';
  }

  return {
    fullFee: course.fullFee,
    subsidyRate,
    subsidyAmount,
    feeAfterSubsidy,
    creditApplied,
    creditSourceLabel,
    outOfPocket,
    isFullyCovered: outOfPocket === 0,
    openingCreditUsed,
    midCareerCreditUsed,
  };
}

export function getRatingDescriptor(score: number): string {
  if (score >= 9.4) return 'Exceptional';
  if (score >= 9.0) return 'Superb';
  if (score >= 8.5) return 'Very Good';
  return 'Good';
}

